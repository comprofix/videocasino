// The return is estimated by playing a great many hands, which takes a
// while. It is played only with -long; -update writes what it counts into
// estimate.go.
var (
	long   = flag.Bool("long", false, "run the slow estimate, which takes a minute or more")
	update = flag.Bool("update", false, "with -long, write the counted figures into estimate.go")
)

// How the estimate is played: so many runs of so many hands each, every
// run from a seed of its own, so that the runs can be played side by side
// and the same count comes out every time.
const (
	estimateRuns    = 16
	estimatePerRun  = 8_000_000
	estimateSeedTag = 0x7061_6967_6f77 // "paigow", to keep these seeds apart
)

// estimateCount is how the hands came out.
type estimateCount struct{ won, pushed, lost int }

// playRun plays one run of hands, each set the house way on both sides.
func playRun(r Ranker, run int) estimateCount {
	var seed [32]byte
	binary.LittleEndian.PutUint64(seed[:], estimateSeedTag)
	binary.LittleEndian.PutUint64(seed[8:], uint64(run))
	rng := rand.New(rand.NewChaCha8(seed))
	var next []cards.Card
	var ec estimateCount
	for range estimatePerRun {
		var player, dealer [HandSize]cards.Card
		draw(rng, &next, player[:])
		draw(rng, &next, dealer[:], player[:]...)
		p, _ := r.Set(player, r.HouseWay(player))
		d, _ := r.Set(dealer, r.HouseWay(dealer))
		switch o, _, _ := Settle(p.High, p.LowS, d.High, d.LowS, 100); o {
		case Won:
			ec.won++
		case Pushed:
			ec.pushed++
		default:
			ec.lost++
		}
	}
	return ec
}

// TestEstimate plays the hands the return is estimated from and checks the
// count kept in estimate.go, which the game shows. It runs only with -long;
// -update writes what it counts into estimate.go.
func TestEstimate(t *testing.T) {
	if !*long {
		t.Skip("takes a minute or more: run with -long -timeout 0")
	}
	start := time.Now()
	r := NewRanker()
	var (
		mu  sync.Mutex
		all estimateCount
		wg  sync.WaitGroup
	)
	for run := range estimateRuns {
		wg.Go(func() {
			ec := playRun(r, run)
			mu.Lock()
			all.won += ec.won
			all.pushed += ec.pushed
			all.lost += ec.lost
			mu.Unlock()
		})
	}
	wg.Wait()
	n := all.won + all.pushed + all.lost
	t.Logf("%d hands played in %v", n, time.Since(start).Round(time.Second))
	t.Logf("won %d, pushed %d, lost %d", all.won, all.pushed, all.lost)
	won := float64(all.won) * 0.95
	t.Logf("return %.4f%%", 100*(1+(won-float64(all.lost))/float64(n)))

	if *update {
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by TestEstimate with -long -update. DO NOT EDIT.\n\n")
		fmt.Fprintf(&b, "package table\n\n")
		fmt.Fprintf(&b, "// How the %d hands TestEstimate played came out.\n", n)
		fmt.Fprintf(&b, "const (\n\testimateWon = %d\n\testimatePushed = %d\n\testimateLost = %d\n)\n", all.won, all.pushed, all.lost)
		src, err := format.Source(b.Bytes())
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile("estimate.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Log("wrote estimate.go")
		return
	}
	if all.won != estimateWon || all.pushed != estimatePushed || all.lost != estimateLost {
		t.Error("the count kept in estimate.go is not the one played: run with -long -update to write it")
	}
}

// TestKept checks the estimate kept in estimate.go against the published
// figures for the game, loosely: this game's house way and ranking are its
// own, so its return can differ a little from any casino's.
func TestKept(t *testing.T) {
	if estimateWon == 0 {
		t.Fatal("no estimate is kept yet: run TestEstimate with -long -update -timeout 0")
	}
	if r := Return(); r < 0.965 || r > 0.985 {
		t.Errorf("the return is %.4f, want about 0.97 to 0.98", r)
	}
	if m := Margin(); m <= 0 || m > 0.0005 {
		t.Errorf("the margin is %.5f", m)
	}
	if _, pushed, _ := Shares(); pushed < 0.35 || pushed > 0.45 {
		t.Errorf("%.3f of hands push, want about 0.4", pushed)
	}
}
